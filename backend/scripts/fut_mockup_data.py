"""Writes docs/mockups/fut-data.js for the FUT-style card draft (docs/mockups/player-cards-fut.html).

Six sub-ratings per skater (40 to 99, from the percentile of weighted KPIs among the 40 skaters of the final, like the
match rating in ratings.py) and three for goalkeepers. Run from the backend folder: python -m scripts.fut_mockup_data"""

import json
from pathlib import Path

from app.content import get_content
from app.ratings import GATED, _num, _percentile, goalie_stats

OUT = Path(__file__).resolve().parents[2] / "docs" / "mockups" / "fut-data.js"
SUB = {  # label -> {stats column: weight}
    "SPD": {"SPD TOP (km/h)": 60, "Sprint SPD-Z DIST (m)": 40},
    "SHO": {"G": 35, "xGsum": 35, "S": 30},
    "PAS": {"A": 40, "Passes": 30, "Pass-%": 30},
    "CTL": {"Control-%": 40, "EPV Total": 30, "Control DIST FWD (m)": 30},
    "DEF": {"BKS": 50, "PCW": 50},
    "PHY": {"TOI (s)": 50, "Dist (m)": 50},
}
PLAYERS = [  # (team, jersey, label shown on the card)
    ("HC Davos", 19, "Sniper"), ("U.S. Collegiate Selects", 18, "Sniper"), ("HC Davos", 70, "Playmaker"),
    ("HC Davos", 66, "Speedster"), ("U.S. Collegiate Selects", 23, "Workhorse"), ("U.S. Collegiate Selects", 2, "Shot Blocker"),
    ("HC Davos", 44, "Chance Creator"), ("HC Davos", 29, "Brick Wall"), ("U.S. Collegiate Selects", 30, "Shot Stopper"),
]


def clamp(x: float) -> float:
    return max(0.0, min(1.0, x))


def main():
    content = get_content()
    rows = content.rows
    pools = {c: [_num(r[c]) for r in rows] for w in SUB.values() for c in w}

    def sub_rating(row: dict, weights: dict) -> int:
        score = 0.0
        for column, weight in weights.items():
            gate = GATED.get(column)
            if gate and _num(row[gate[0]]) < gate[1]:
                continue
            score += weight * _percentile(_num(row[column]), pools[column])
        return round(40 + 59 * score / sum(weights.values()))

    images = {}
    for game in content.testdata.games:
        if game["has_wisehockey"]:
            for p in game["players"]:
                images[(p["team"], p["jersey"])] = p["image_url"]
    goalies = goalie_stats(content.event_rows, content.sides)
    specials = {"motm": "player-of-the-match", "gamewinner": "game-winner", "wall": "brick-wall"}
    wanted = [(t, j, label, None) for t, j, label in PLAYERS]
    for special, card_id in specials.items():
        card = content.cards[card_id]
        wanted.append((card["player"]["team"], card["player"]["jersey"], card["title"], special))
    out = []
    for team, jersey, label, special in wanted:
        cards = [c for c in content.cards.values() if c["player"] and (c["player"]["team"], c["player"]["jersey"]) == (team, jersey)]
        card = next((c for c in cards if c["type"] == "base"), cards[0])
        player = card["player"]
        rating = content.ratings[(team, jersey)]
        entry = {
            "team": team, "jersey": jersey, "first": player["first_name"], "last": player["last_name"],
            "position": player["position"], "nation": (card.get("bio") or {}).get("nationality"), "label": label,
            "mr": rating["mr"], "tier": rating["tier"], "image": images.get((team, jersey)) or player["image_url"],
            "special": special,
        }
        if player["position"] == "Goalkeeper":
            g = goalies[(team, jersey)]
            sv = g["saves"] / g["shots"] if g["shots"] else 0
            hd = g["hd_saves"] / g["hd_shots"] if g["hd_shots"] else 0
            goals_against = g["shots"] - g["saves"]
            entry["stats"] = {
                "SAV": round(40 + 59 * clamp((sv - 0.80) / 0.15)), "HDS": round(40 + 59 * hd),
                "XGS": round(40 + 59 * clamp((g["xg"] - goals_against + 2) / 4)),
            }
        else:
            row = next(r for r in rows if r["Team"] == team and int(r["Jersey"]) == jersey)
            entry["stats"] = {name: sub_rating(row, weights) for name, weights in SUB.items()}
        out.append(entry)
    OUT.write_text("// Generated by backend/scripts/fut_mockup_data.py. Sub-ratings are percentile based, see the script.\n"
                   "window.FUT_DATA = " + json.dumps(out, ensure_ascii=False, indent=1) + ";\n", encoding="utf-8")
    for e in out:
        print(e["team"], e["jersey"], e["last"], e["mr"], e["stats"], e["nation"])


if __name__ == "__main__":
    main()
